CREATE TABLE vet_credential_documents (
                                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                          vet_user_id BIGINT NOT NULL
                                              REFERENCES users(id) ON DELETE CASCADE,

                                          document_type VARCHAR(40) NOT NULL
                                              CHECK (
                                                  document_type IN (
                                                                    'DEGREE_CERTIFICATE',
                                                                    'REGISTRATION_CERTIFICATE',
                                                                    'ADDITIONAL_CERTIFICATE'
                                                      )
                                                  ),

                                          original_file_name VARCHAR(255) NOT NULL,

                                          stored_file_name VARCHAR(255) NOT NULL UNIQUE,

                                          content_type VARCHAR(100) NOT NULL,

                                          file_size BIGINT NOT NULL
                                              CHECK (file_size > 0),

                                          verification_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                                              CHECK (
                                                  verification_status IN (
                                                                          'PENDING',
                                                                          'APPROVED',
                                                                          'REJECTED'
                                                      )
                                                  ),

                                          admin_notes TEXT,

                                          uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                          reviewed_at TIMESTAMP,

                                          reviewed_by BIGINT REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_vet_credential_documents_vet_user_id
    ON vet_credential_documents(vet_user_id);

CREATE INDEX idx_vet_credential_documents_status
    ON vet_credential_documents(verification_status);
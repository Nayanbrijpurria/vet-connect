-- Keep a pet's history after the customer removes it from their active list.
ALTER TABLE pets ADD COLUMN archived_at TIMESTAMPTZ;

-- Existing code checks ownership when booking; promote this invariant to the database.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM appointments a
        JOIN pets p ON p.id = a.pet_id
        WHERE a.customer_id <> p.owner_id
    ) THEN
        RAISE EXCEPTION 'Cannot add appointment ownership constraint: appointments exist for pets owned by another customer';
    END IF;
END $$;

ALTER TABLE pets ADD CONSTRAINT uq_pets_id_owner UNIQUE (id, owner_id);
ALTER TABLE appointments
    ADD CONSTRAINT fk_appointment_customer_owns_pet
    FOREIGN KEY (pet_id, customer_id) REFERENCES pets(id, owner_id);

ALTER TABLE vet_profiles ADD CONSTRAINT uq_vet_profiles_id_user UNIQUE (id, user_id);

CREATE TABLE pet_allergies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id BIGINT NOT NULL REFERENCES pets(id) ON DELETE RESTRICT,
    allergen VARCHAR(200) NOT NULL,
    reaction TEXT,
    severity VARCHAR(20) CHECK (severity IN ('MILD', 'MODERATE', 'SEVERE', 'UNKNOWN')),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'RESOLVED')),
    identified_at DATE,
    recorded_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    recorded_by_vet_profile_id BIGINT REFERENCES vet_profiles(id) ON DELETE RESTRICT,
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pet_allergy_recorder_vet FOREIGN KEY (recorded_by_vet_profile_id, recorded_by) REFERENCES vet_profiles(id, user_id),
    CHECK ((verified_at IS NULL) = (recorded_by_vet_profile_id IS NULL))
);
CREATE INDEX idx_pet_allergies_pet_status ON pet_allergies(pet_id, status, created_at DESC);

CREATE TABLE pet_conditions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id BIGINT NOT NULL REFERENCES pets(id) ON DELETE RESTRICT,
    condition_name VARCHAR(200) NOT NULL,
    condition_code VARCHAR(100),
    details TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'CHRONIC', 'RESOLVED')),
    diagnosed_at DATE,
    recorded_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    recorded_by_vet_profile_id BIGINT REFERENCES vet_profiles(id) ON DELETE RESTRICT,
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pet_condition_recorder_vet FOREIGN KEY (recorded_by_vet_profile_id, recorded_by) REFERENCES vet_profiles(id, user_id),
    CHECK ((verified_at IS NULL) = (recorded_by_vet_profile_id IS NULL))
);
CREATE INDEX idx_pet_conditions_pet_status ON pet_conditions(pet_id, status, created_at DESC);

CREATE TABLE pet_vaccinations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id BIGINT NOT NULL REFERENCES pets(id) ON DELETE RESTRICT,
    vaccine_name VARCHAR(200) NOT NULL,
    administered_at TIMESTAMPTZ NOT NULL,
    dose VARCHAR(100),
    route VARCHAR(100),
    manufacturer VARCHAR(200),
    batch_number VARCHAR(100),
    next_due_at DATE,
    notes TEXT,
    recorded_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    administered_by_vet_profile_id BIGINT REFERENCES vet_profiles(id) ON DELETE RESTRICT,
    verified_at TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'RECORDED' CHECK (status IN ('RECORDED', 'VOIDED')),
    correction_reason TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pet_vaccination_recorder_vet FOREIGN KEY (administered_by_vet_profile_id, recorded_by) REFERENCES vet_profiles(id, user_id),
    CHECK ((verified_at IS NULL) = (administered_by_vet_profile_id IS NULL)),
    CHECK ((status = 'VOIDED' AND correction_reason IS NOT NULL AND LENGTH(TRIM(correction_reason)) > 0) OR (status = 'RECORDED' AND correction_reason IS NULL))
);
CREATE INDEX idx_pet_vaccinations_pet_date ON pet_vaccinations(pet_id, administered_at DESC);

-- Corrections are appended; the original consultation remains unchanged.
CREATE TABLE consultation_amendments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id BIGINT NOT NULL REFERENCES consultations(id) ON DELETE RESTRICT,
    author_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    amendment TEXT NOT NULL CHECK (LENGTH(TRIM(amendment)) > 0),
    reason TEXT NOT NULL CHECK (LENGTH(TRIM(reason)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_consultation_amendments_consultation ON consultation_amendments(consultation_id, created_at DESC);


-- V5: Medical records foundation for VetPlatform

-- 1. A consultation belongs to an existing appointment.
CREATE TABLE consultations (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               appointment_id BIGINT NOT NULL UNIQUE
                                   REFERENCES appointments(id) ON DELETE RESTRICT,

                               pet_id BIGINT NOT NULL
                                   REFERENCES pets(id) ON DELETE RESTRICT,

                               vet_profile_id BIGINT NOT NULL
                                   REFERENCES vet_profiles(id) ON DELETE RESTRICT,

                               chief_complaint TEXT,
                               clinical_notes TEXT,
                               diagnosis TEXT,
                               treatment_notes TEXT,
                               follow_up_notes TEXT,

                               created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                               updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_consultations_pet_created
    ON consultations(pet_id, created_at DESC);

-- 2. Store document metadata, not the actual PDF or image.
-- Files will eventually live in private object storage.
CREATE TABLE medical_documents (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                   pet_id BIGINT NOT NULL
                                       REFERENCES pets(id) ON DELETE RESTRICT,

                                   consultation_id BIGINT
                                       REFERENCES consultations(id) ON DELETE RESTRICT,

                                   uploaded_by BIGINT NOT NULL
                                       REFERENCES users(id) ON DELETE RESTRICT,

                                   document_type VARCHAR(40) NOT NULL
                                       CHECK (document_type IN (
                                                                'LAB_REPORT',
                                                                'PRESCRIPTION',
                                                                'MEDICAL_HISTORY',
                                                                'IMAGING',
                                                                'OTHER'
                                           )),

                                   original_filename VARCHAR(255) NOT NULL,
                                   storage_key TEXT NOT NULL UNIQUE,
                                   mime_type VARCHAR(100) NOT NULL,
                                   file_size_bytes BIGINT NOT NULL
                                       CHECK (file_size_bytes > 0),

                                   processing_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                                       CHECK (processing_status IN (
                                                                    'PENDING',
                                                                    'PROCESSING',
                                                                    'COMPLETED',
                                                                    'FAILED'
                                           )),

                                   uploaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_medical_documents_pet
    ON medical_documents(pet_id, uploaded_at DESC);

CREATE INDEX idx_medical_documents_consultation
    ON medical_documents(consultation_id);

-- 3. Store structured observations from reports and tests.
CREATE TABLE clinical_observations (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                       pet_id BIGINT NOT NULL
                                           REFERENCES pets(id) ON DELETE RESTRICT,

                                       consultation_id BIGINT
                                           REFERENCES consultations(id) ON DELETE RESTRICT,

                                       document_id BIGINT
                                           REFERENCES medical_documents(id) ON DELETE RESTRICT,

                                       test_name VARCHAR(200) NOT NULL,
                                       test_code VARCHAR(100),

                                       numeric_value NUMERIC,
                                       text_value TEXT,
                                       unit VARCHAR(50),

                                       reference_range_low NUMERIC,
                                       reference_range_high NUMERIC,

                                       observed_at TIMESTAMPTZ NOT NULL,

                                       verification_status VARCHAR(20) NOT NULL DEFAULT 'UNVERIFIED'
                                           CHECK (verification_status IN (
                                                                          'UNVERIFIED',
                                                                          'VERIFIED',
                                                                          'REJECTED'
                                               )),

                                       verified_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
                                       verified_at TIMESTAMPTZ,

                                       source_details JSONB NOT NULL DEFAULT '{}'::jsonb,

                                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                       CHECK (numeric_value IS NOT NULL OR text_value IS NOT NULL),

                                       CHECK (
                                           (verification_status = 'VERIFIED'
                                               AND verified_by IS NOT NULL
                                               AND verified_at IS NOT NULL)
                                               OR
                                           (verification_status <> 'VERIFIED'
                                               AND verified_by IS NULL
                                               AND verified_at IS NULL)
                                           )
);

CREATE INDEX idx_clinical_observations_pet_date
    ON clinical_observations(pet_id, observed_at DESC);

CREATE INDEX idx_clinical_observations_document
    ON clinical_observations(document_id);

-- 4. Store a prescription issued during a consultation.
CREATE TABLE prescriptions (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               consultation_id BIGINT NOT NULL
                                   REFERENCES consultations(id) ON DELETE RESTRICT,

                               pet_id BIGINT NOT NULL
                                   REFERENCES pets(id) ON DELETE RESTRICT,

                               vet_profile_id BIGINT NOT NULL
                                   REFERENCES vet_profiles(id) ON DELETE RESTRICT,

                               prescription_number VARCHAR(100) NOT NULL UNIQUE,
                               diagnosis TEXT,
                               instructions TEXT,
                               follow_up_at TIMESTAMPTZ,

                               status VARCHAR(20) NOT NULL DEFAULT 'ISSUED'
                                   CHECK (status IN (
                                                     'DRAFT',
                                                     'ISSUED',
                                                     'CANCELLED'
                                       )),

                               issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                               created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_prescriptions_pet
    ON prescriptions(pet_id, issued_at DESC);

CREATE INDEX idx_prescriptions_consultation
    ON prescriptions(consultation_id);

-- 5. Store each medicine separately.
CREATE TABLE prescription_items (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                    prescription_id BIGINT NOT NULL
                                        REFERENCES prescriptions(id) ON DELETE RESTRICT,

                                    medicine_name VARCHAR(255) NOT NULL,
                                    dosage VARCHAR(255) NOT NULL,
                                    frequency VARCHAR(255) NOT NULL,
                                    duration VARCHAR(100) NOT NULL,
                                    route VARCHAR(100),
                                    instructions TEXT,

                                    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_prescription_items_prescription
    ON prescription_items(prescription_id);

-- 6. Record sensitive access and changes for auditing.
CREATE TABLE audit_logs (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                            actor_user_id BIGINT
                                REFERENCES users(id) ON DELETE RESTRICT,

                            action VARCHAR(100) NOT NULL,
                            entity_type VARCHAR(100) NOT NULL,
                            entity_id BIGINT,

                            details JSONB NOT NULL DEFAULT '{}'::jsonb,

                            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_audit_logs_actor_date
    ON audit_logs(actor_user_id, created_at DESC);

CREATE INDEX idx_audit_logs_entity
    ON audit_logs(entity_type, entity_id);


-- Ensure consultations match their actual appointment.
ALTER TABLE appointments
    ADD CONSTRAINT uq_appointments_id_pet_vet
        UNIQUE (id, pet_id, vet_profile_id);

ALTER TABLE consultations
    ADD CONSTRAINT fk_consultation_matching_appointment
        FOREIGN KEY (appointment_id, pet_id, vet_profile_id)
            REFERENCES appointments (id, pet_id, vet_profile_id);

-- Ensure prescriptions match their consultation's pet and vet.
ALTER TABLE consultations
    ADD CONSTRAINT uq_consultations_id_pet_vet
        UNIQUE (id, pet_id, vet_profile_id);

ALTER TABLE prescriptions
    ADD CONSTRAINT fk_prescription_matching_consultation
        FOREIGN KEY (consultation_id, pet_id, vet_profile_id)
            REFERENCES consultations (id, pet_id, vet_profile_id);


-- Ensure documents belong to the same pet as their consultation.
ALTER TABLE consultations
    ADD CONSTRAINT uq_consultations_id_pet
        UNIQUE (id, pet_id);

ALTER TABLE medical_documents
    ADD CONSTRAINT uq_medical_documents_id_pet
        UNIQUE (id, pet_id);

ALTER TABLE medical_documents
    ADD CONSTRAINT fk_medical_documents_consultation_pet
        FOREIGN KEY (consultation_id, pet_id)
            REFERENCES consultations (id, pet_id);

-- Ensure observations match their linked consultation and document.
ALTER TABLE clinical_observations
    ADD CONSTRAINT fk_observations_consultation_pet
        FOREIGN KEY (consultation_id, pet_id)
            REFERENCES consultations (id, pet_id);

ALTER TABLE clinical_observations
    ADD CONSTRAINT fk_observations_document_pet
        FOREIGN KEY (document_id, pet_id)
            REFERENCES medical_documents (id, pet_id);

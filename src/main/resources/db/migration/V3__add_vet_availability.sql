
-- Store each veterinarian's local timezone.
ALTER TABLE vet_profiles
    ADD COLUMN timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Kolkata';

-- Store the weekly working hours of each veterinarian.
CREATE TABLE vet_availability (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                  vet_profile_id BIGINT NOT NULL
                                      REFERENCES vet_profiles(user_id) ON DELETE CASCADE,

    -- ISO weekday: Monday = 1, Sunday = 7
                                  day_of_week SMALLINT NOT NULL
                                      CHECK (day_of_week BETWEEN 1 AND 7),

                                  start_time TIME NOT NULL,
                                  end_time TIME NOT NULL,

                                  slot_duration_minutes SMALLINT NOT NULL DEFAULT 30
                                      CHECK (slot_duration_minutes BETWEEN 10 AND 240),

                                  active BOOLEAN NOT NULL DEFAULT TRUE,
                                  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                  CHECK (end_time > start_time),

                                  UNIQUE (vet_profile_id, day_of_week, start_time, end_time)
);

CREATE INDEX idx_vet_availability_profile_day_active
    ON vet_availability (vet_profile_id, day_of_week, active);

-- Store periods when a veterinarian is unavailable.
CREATE TABLE vet_time_off (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                              vet_profile_id BIGINT NOT NULL
                                  REFERENCES vet_profiles(user_id) ON DELETE CASCADE,

                              starts_at TIMESTAMPTZ NOT NULL,
                              ends_at TIMESTAMPTZ NOT NULL,

                              reason VARCHAR(250),
                              created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                              CHECK (ends_at > starts_at)
);

CREATE INDEX idx_vet_time_off_profile_range
    ON vet_time_off (vet_profile_id, starts_at, ends_at);
